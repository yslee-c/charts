def resolve_symbol(text: str) -> str:
    """把用户输入解析成主力连续代码。

    - 命中中文名/别名 → 对应代码；
    - 已经是代码（字母+可选0/数字）→ 原样大写返回；
    - 其它 → 大写返回（交给数据源，失败会有友好报错）。
    """
    s = (text or "").strip()
    if s in _NAME_TO_CODE:
        return _NAME_TO_CODE[s]
    # 去掉常见后缀再试（如「沪锡主连」「螺纹钢期货」）
    for suffix in ("主力连续", "主力", "主连", "期货", "指数"):
        if s.endswith(suffix) and s[: -len(suffix)] in _NAME_TO_CODE:
            return _NAME_TO_CODE[s[: -len(suffix)]]
    return s.upper()
